export type GlassType = "templado" | "laminado" | "crudo" | "dvh" | "espejos" | "planchas";

export interface CalculationOptions {
  urgent: boolean;
  bordePulido?: boolean; // <-- Nueva opción
  calados?: number;
  pasaVoz?: boolean;
  puntasRedondeadas?: boolean;
  camaraMm?: 6 | 9 | 12;
  vidrioSecundarioIndex?: number;
}

/**
 * LÓGICA DE CÁLCULO MEJORADA
 * Se añade el parámetro 'shouldPolish'
 */
function calculateBasePiece(
  pricePerM2: number, 
  widthMm: number, 
  heightMm: number, 
  thickness: number, 
  shouldPolish: boolean, // <-- Nuevo parámetro
  type?: string
): number {
  const widthM = widthMm / 1000;
  const heightM = heightMm / 1000;
  let area = widthM * heightM;
  const perimeter = (widthM + heightM) * 2;

  // 1. Mínimo 0.5 m2
  const areaForPrice = area < 0.5 ? 0.5 : area;
  let price = areaForPrice * pricePerM2;

  // 2. Recargo por grandes dimensiones (> 4.6 m2)

  if (area > 4.5 && type !== 'planchas') price *= 1.2;

  // 3. Borde pulido: SOLO se suma si shouldPolish es true
  if (shouldPolish) {
    const costPerLinealMeter = thickness >= 12 ? 3255 : 1627.5;
    price += perimeter * costPerLinealMeter;
  }

  return price;
}

export function calculatePrice(
  type: GlassType,
  glassIndex: number,
  widthMm: number,
  heightMm: number,
  quantity: number,
  options: CalculationOptions
): { areaM2: number; unitPrice: number; totalPrice: number; peso: number} {
  const mainGlass = rawGlassData[glassIndex] as any;
  const areaReal = (widthMm / 1000) * (heightMm / 1000);
  let unitPrice = 0;
  let peso = 0

  if(type === 'dvh'){
    const espesorGlass = (rawGlassData[options.vidrioSecundarioIndex ?? glassIndex] as any);
    peso = ((areaReal * 2.5 * mainGlass.espesor) + (areaReal * 2.5 * espesorGlass.espesor)) * quantity
  }else{
    peso = (areaReal * 2.5 * mainGlass.espesor) * quantity
  }

  // REGLA: El templado SIEMPRE lleva borde pulido por proceso. 
  // Para los demás, depende de lo que elija el usuario.
  const needsPolish = !!options.bordePulido;

  switch (type) {
    case "crudo":
      unitPrice = calculateBasePiece(mainGlass["Precio para DVH"] || 0, widthMm, heightMm, mainGlass.espesor, needsPolish, type);
      if (options.calados) unitPrice += options.calados * 1575;
      break
    case "espejos":
    case "planchas":
      unitPrice = calculateBasePiece(mainGlass["precio para crudo"] || 0, widthMm, heightMm, mainGlass.espesor, needsPolish, type);
      break;

    case "templado":
      // El templado siempre usa 'true' en pulido
      unitPrice = calculateBasePiece(mainGlass["Precio Templado"] || 0, widthMm, heightMm, mainGlass.espesor, needsPolish);
      if (options.calados) unitPrice += options.calados * 1575;
      if (options.pasaVoz) unitPrice += 8736;
      if (options.puntasRedondeadas) unitPrice += 5460;
      break;

    case "laminado":
      const v1Price = calculateBasePiece(mainGlass["Precio para Laminado"] || 0, widthMm, heightMm, mainGlass.espesor, needsPolish);
      const secondGlass = (rawGlassData[options.vidrioSecundarioIndex ?? glassIndex] as any);
      const v2Price = calculateBasePiece(secondGlass["Precio para Laminado"] || 0, widthMm, heightMm, secondGlass.espesor, needsPolish);

      const areaMinPVB = areaReal < 0.5 ? 0.5 : areaReal;
      unitPrice = v1Price + v2Price + (areaMinPVB * 79750);
      if (options.calados) unitPrice += options.calados * 1575;
      break;

    case "dvh":
      // En DVH el pulido suele ser opcional/estético ya que los bordes van dentro del perfil
      const vi = calculateBasePiece(mainGlass["Precio para DVH"] || 0, widthMm, heightMm, mainGlass.espesor, needsPolish);
      const extG = (rawGlassData[options.vidrioSecundarioIndex ?? glassIndex] as any);
      const ve = calculateBasePiece(extG["Precio para DVH"] || 0, widthMm, heightMm, extG.espesor, needsPolish);

      const perimetroM = ((widthMm + heightMm) * 2) / 1000;
      const costCamara = options.camaraMm === 12 ? 6505 : options.camaraMm === 9 ? 5034 : 4520;
      unitPrice = vi + ve + (perimetroM * costCamara);
      if (options.calados) unitPrice += options.calados * 3150;
      break;
  }

  if (options.urgent) unitPrice *= 1.5;

  return {
    areaM2: areaReal,
    unitPrice,
    totalPrice: unitPrice * quantity,
    peso: peso
  };
}

export function formatARS(value: number): string {
  return new Intl.NumberFormat("es-AR", {
    style: "currency",
    currency: "ARS",
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(value);
}
